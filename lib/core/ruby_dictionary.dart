/// 辞書を引く。文字列を、ふりがな付きの部分と、そのままの部分に分ける。
class RubyDictionary {
  RubyDictionary._();

  static final _kanji = RegExp(r'[一-鿿々〆ヶ]');

  static bool hasKanji(String s) => _kanji.hasMatch(s);

  /// 語（かなを含む）→ 部分の並び（base と、ふりがな。ふりがなが null なら、そのままの文字）。
  static final Map<String, List<RubySegment>> _words = {};
  static final Map<String, List<RubySegment>> _wholeOnly = {};
  static int _maxLen = 1;
  static bool _ready = false;

  static void _init() {
    if (_ready) return;
    _ready = true;
    final token = RegExp(r'([^()]+)\(([^()]+)\)|([^()]+)');
    for (final raw in rubyEntries) {
      final whole = raw.startsWith('=');
      final entry = whole ? raw.substring(1) : raw;
      final segs = <RubySegment>[];
      final key = StringBuffer();
      for (final m in token.allMatches(entry)) {
        if (m.group(1) != null) {
          // 「漢字(よみ)」。base の手前にかながあれば（例：「見(み)」の前）は切り分ける。
          final base = m.group(1)!;
          final kanjiStart = base.indexOf(_kanji);
          if (kanjiStart > 0) {
            segs.add(RubySegment(base.substring(0, kanjiStart), null));
          }
          final b = kanjiStart > 0 ? base.substring(kanjiStart) : base;
          segs.add(RubySegment(b, m.group(2)));
          key.write(base);
        } else {
          final t = m.group(3)!;
          segs.add(RubySegment(t, null));
          key.write(t);
        }
      }
      final k = key.toString();
      (whole ? _wholeOnly : _words)[k] = segs;
      if (!whole && k.length > _maxLen) _maxLen = k.length;
    }
  }

  /// [text] を分ける。辞書にない漢字は、そのまま（ふりがななし）。
  static List<RubySegment> segment(String text) {
    _init();
    final whole = _wholeOnly[text.trim()];
    if (whole != null) return whole;
    final out = <RubySegment>[];
    final plain = StringBuffer();
    void flush() {
      if (plain.isNotEmpty) {
        out.add(RubySegment(plain.toString(), null));
        plain.clear();
      }
    }

    var i = 0;
    while (i < text.length) {
      List<RubySegment>? hit;
      var len = 0;
      if (_kanji.hasMatch(text[i])) {
        for (var l = (text.length - i).clamp(1, _maxLen); l >= 1; l--) {
          final segs = _words[text.substring(i, i + l)];
          if (segs != null) {
            hit = segs;
            len = l;
            break;
          }
        }
      }
      if (hit == null) {
        plain.write(text[i]);
        i++;
      } else {
        flush();
        out.addAll(hit);
        i += len;
      }
    }
    flush();
    return out;
  }
}

/// ふりがな付きの1かたまり。[ruby] が null のときは、ふりがなを付けない。
class RubySegment {
  const RubySegment(this.base, this.ruby);
  final String base;
  final String? ruby;
}
